  /// Lowercase, strip accents, and reduce everything that is not a Latin
  /// letter to single spaces.
  static String fold(String text) {
    final lower = text.toLowerCase();
    final buffer = StringBuffer();
    for (final rune in lower.runes) {
      final char = String.fromCharCode(rune);
      buffer.write(_accents[char] ?? char);
    }
    return buffer.toString().replaceAll(RegExp(r'[^a-z]+'), ' ').trim();
  }

  static List<String> tokens(String text) {
    final folded = fold(text);
    return folded.isEmpty ? const [] : folded.split(' ');
  }

  /// True when [text] names a household/pet/pharmacy item, a bag or a
  /// deposit — never something to stock as food.
  static bool isNonFood(String text) {
    final words = tokens(text);
    if (words.isEmpty) return false;
    final folded = words.join(' ');
    for (final term in _nonFoodFolded) {
      if (term.contains(' ')) {
        if (' $folded '.contains(' $term ')) return true;
      } else if (words.contains(term)) {
        return true;
      }
    }
    // Compound nouns such as "Hundefutter" / "Plastiktüte".
    for (final word in words) {
      if (word.length < 6) continue;
      for (final term in _nonFoodFolded) {
        if (term.length >= 5 && !term.contains(' ') && word.endsWith(term)) {
          return true;
        }
      }
    }
    return false;
  }

  /// Best canonical food/drink for [text], or null when it names no food.
  ///
  /// Priority: exact multi-word phrase > exact word > compound head
  /// (Dutch/German "Vollmilch" → milk) > inflection (Polish "pomidory").
  /// Ties prefer the longer term, then the earlier position.
  static String? match(String text) {
    if (isNonFood(text)) return null;
    final words = tokens(text);
    if (words.isEmpty) return null;
    final idx = index;
    String? best;
    var bestRank = -1;
    var bestLength = 0;
    void consider(String? canonical, int rank, int length) {
      if (canonical == null) return;
      if (rank > bestRank || (rank == bestRank && length > bestLength)) {
        best = canonical;
        bestRank = rank;
        bestLength = length;
      }
    }

    for (var n = 4; n >= 2; n--) {
      for (var i = 0; i + n <= words.length; i++) {
        final phrase = words.sublist(i, i + n).join(' ');
        consider(idx[phrase], 3, phrase.length);
      }
    }
    for (final word in words) {
      if (word.length < 2) continue;
      consider(idx[word], 2, word.length);
    }
    if (bestRank < 2) {
      for (final word in words) {
        if (word.length < 6) continue;
        for (final entry in idx.entries) {
          final term = entry.key;
          if (term.length < 4 || term.contains(' ')) continue;
          if (word.length >= term.length + 2 && word.endsWith(term)) {
            consider(entry.value, 1, term.length);
          }
        }
      }
    }
    if (bestRank < 1) {
      for (final word in words) {
        if (word.length < 5) continue;
        for (final entry in idx.entries) {
          final term = entry.key;
          if (term.length < 5 || term.contains(' ')) continue;
          final stem = RegExp(r'[aeiou]$').hasMatch(term)
              ? term.substring(0, term.length - 1)
              : term;
          if (word.startsWith(stem) && word.length <= term.length + 3) {
            consider(entry.value, 0, term.length);
          }
        }
      }
    }
    return best;
  }
