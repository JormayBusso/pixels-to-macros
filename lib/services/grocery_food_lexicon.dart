  static Map<String, String>? _index;

  /// Accent-folded term -> canonical name.
  static Map<String, String> get index {
    final existing = _index;
    if (existing != null) return existing;
    final map = <String, String>{};
    _foods.forEach((canonical, terms) {
      map.putIfAbsent(fold(canonical), () => canonical);
      for (final term in terms) {
        map.putIfAbsent(fold(term), () => canonical);
      }
    });
    _index = map;
    return map;
  }

